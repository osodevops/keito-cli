#!/usr/bin/env python3
"""Outer source collection; import-safe bounded no-Git verification inside policy."""
from pathlib import Path, PurePosixPath
import datetime
import hashlib
import json
import os
import stat
import subprocess
import sys

MAX_FILES = 4096
MAX_FILE_BYTES = 16 * 1024 * 1024
MAX_TOTAL_BYTES = 64 * 1024 * 1024
MAX_MANIFEST_BYTES = 2 * 1024 * 1024
MANIFEST_NAME = "source-qa-manifest.json"
COLLECTOR_NAME = "tests/support/source_qa_manifest.py"
COMPLETENESS = {"tracked": True, "untracked_nonignored": True, "deleted_tracked": True,
                "fsmonitor": False, "hooks": False, "global_config": False,
                "optional_locks": False}


class ManifestError(RuntimeError):
    pass


def closed_object(pairs):
    value = {}
    for key, entry in pairs:
        if key in value:
            raise ManifestError("duplicate source manifest field")
        value[key] = entry
    return value


def canonical_root(path, private=False):
    path = Path(path)
    metadata = path.lstat()
    if (not path.is_absolute() or path.resolve(strict=True) != path or not stat.S_ISDIR(metadata.st_mode)
            or metadata.st_uid != os.getuid() or (private and stat.S_IMODE(metadata.st_mode) != 0o700)):
        raise ManifestError("invalid owned canonical root")
    return path


def safe_name(name):
    if (not isinstance(name, str) or not name or len(name.encode()) > 2048 or "\\" in name
            or any(ord(value) < 32 or ord(value) == 127 for value in name)):
        raise ManifestError("unsafe source name")
    path = PurePosixPath(name)
    if path.is_absolute() or any(part in ("", ".", "..") for part in name.split("/")) or path.parts[0] == ".git":
        raise ManifestError("unsafe source name")
    if "__pycache__" in path.parts or name.endswith((".pyc", ".pyo")):
        raise ManifestError("generated bytecode is not source")
    return path.parts


def open_parent(repo, name):
    parts = safe_name(name)
    descriptor = os.open(repo, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC)
    try:
        for part in parts[:-1]:
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=descriptor)
            metadata = os.fstat(child)
            if metadata.st_uid != os.getuid():
                os.close(child)
                raise ManifestError("foreign source directory")
            os.close(descriptor)
            descriptor = child
        return descriptor, parts[-1]
    except BaseException:
        os.close(descriptor)
        raise


def stamp(metadata):
    return (metadata.st_dev, metadata.st_ino, metadata.st_uid, metadata.st_mode,
            metadata.st_nlink, metadata.st_size, metadata.st_mtime_ns, metadata.st_ctime_ns)


def source_record(repo, name):
    directory, leaf = open_parent(repo, name)
    try:
        descriptor = os.open(leaf, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | os.O_CLOEXEC, dir_fd=directory)
        try:
            before = os.fstat(descriptor)
            if (not stat.S_ISREG(before.st_mode) or before.st_uid != os.getuid() or before.st_nlink != 1
                    or before.st_size > MAX_FILE_BYTES):
                raise ManifestError("unsafe or oversized source")
            value = hashlib.sha256()
            size = 0
            while True:
                block = os.read(descriptor, 64 * 1024)
                if not block:
                    break
                size += len(block)
                if size > MAX_FILE_BYTES:
                    raise ManifestError("oversized source")
                value.update(block)
            named = os.stat(leaf, dir_fd=directory, follow_symlinks=False)
            if size != before.st_size or stamp(before) != stamp(os.fstat(descriptor)) or stamp(before) != stamp(named):
                raise ManifestError("source changed during snapshot")
            return {"sha256": value.hexdigest(), "bytes": size, "mode": stat.S_IMODE(before.st_mode)}
        finally:
            os.close(descriptor)
    finally:
        os.close(directory)


def require_absent(repo, name):
    try:
        directory, leaf = open_parent(repo, name)
    except FileNotFoundError:
        return
    try:
        try:
            os.stat(leaf, dir_fd=directory, follow_symlinks=False)  # lstat semantics, no target read.
        except FileNotFoundError:
            return
        raise ManifestError("deleted source path reappeared")
    finally:
        os.close(directory)


def source_set_digest(files, deleted):
    return hashlib.sha256(json.dumps({"files": files, "deleted_paths": deleted}, sort_keys=True,
                                     separators=(",", ":")).encode()).hexdigest()


def snapshot(repo, names, deleted):
    if len(names) + len(deleted) > MAX_FILES or set(names) & set(deleted):
        raise ManifestError("invalid source membership")
    files = {}
    total = 0
    for name in sorted(names):
        files[name] = source_record(repo, name)
        total += files[name]["bytes"]
        if total > MAX_TOTAL_BYTES:
            raise ManifestError("source set too large")
    for name in deleted:
        require_absent(repo, name)
    return files


def git_members(repo):
    """OUTER ONLY. No caller in the inherited runner invokes this function."""
    environment = {"PATH": "/usr/bin:/bin", "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null",
                   "GIT_CONFIG_NOSYSTEM": "1", "GIT_OPTIONAL_LOCKS": "0", "GIT_TERMINAL_PROMPT": "0"}
    command = ["/usr/bin/git", "-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null",
               "-c", "submodule.recurse=false", "-C", str(repo)]

    def query(arguments):
        # Git remains in the outer caller's group, with no detached child group.
        output = subprocess.check_output(command + arguments, env=environment, timeout=60)
        if len(output) > MAX_MANIFEST_BYTES:
            raise ManifestError("source Git inventory output too large")
        return output

    top = query(["rev-parse", "--show-toplevel"]).decode().strip()
    if top != str(repo):
        raise ManifestError("Git root mismatch")
    head = query(["rev-parse", "HEAD"]).decode().strip()
    if len(head) != 40 or any(value not in "0123456789abcdef" for value in head):
        raise ManifestError("invalid source head")
    names = query(["ls-files", "--cached", "--others", "--exclude-standard", "-z"]).decode().split("\0")[:-1]
    deleted = query(["ls-files", "--deleted", "-z"]).decode().split("\0")[:-1]
    if len(names) > MAX_FILES or len(deleted) > MAX_FILES:
        raise ManifestError("source membership too large")
    if len(names) != len(set(names)) or len(deleted) != len(set(deleted)) or not set(deleted) <= set(names):
        raise ManifestError("ambiguous source membership")
    for name in names:
        safe_name(name)
    return head, sorted(set(names) - set(deleted)), sorted(deleted)


def collect(repo, parent):
    repo, parent = canonical_root(repo), canonical_root(parent, private=True)
    head, names, deleted = git_members(repo)
    files = snapshot(repo, names, deleted)
    if COLLECTOR_NAME not in files:
        raise ManifestError("collector not included in source set")
    value = {"schema_version": 1, "repo": str(repo), "head_sha": head,
             "collector": {"name": COLLECTOR_NAME, "sha256": files[COLLECTOR_NAME]["sha256"]},
             "completeness": COMPLETENESS, "files": files, "deleted_paths": deleted,
             "source_set_sha256": source_set_digest(files, deleted),
             "created_utc": datetime.datetime.now(datetime.timezone.utc).isoformat()}
    raw = (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()
    if len(raw) > MAX_MANIFEST_BYTES:
        raise ManifestError("manifest too large")
    descriptor = os.open(parent / MANIFEST_NAME, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600)
    with os.fdopen(descriptor, "wb") as output:
        output.write(raw)
        output.flush()
        os.fsync(output.fileno())
    return hashlib.sha256(raw).hexdigest()


class ManifestLease:
    def __init__(self, repo, parent):
        self.repo, self.parent = canonical_root(repo), canonical_root(parent, private=True)
        self.descriptor = os.open(self.parent / MANIFEST_NAME, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        try:
            metadata = os.fstat(self.descriptor)
            if (not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != os.getuid() or metadata.st_nlink != 1
                    or stat.S_IMODE(metadata.st_mode) != 0o600 or metadata.st_size > MAX_MANIFEST_BYTES):
                raise ManifestError("unsafe source manifest")
            self.raw = os.read(self.descriptor, MAX_MANIFEST_BYTES + 1)
            if len(self.raw) != metadata.st_size or stamp(metadata) != stamp(os.fstat(self.descriptor)):
                raise ManifestError("source manifest changed")
            self.before = stamp(metadata)
            self.raw_sha256 = hashlib.sha256(self.raw).hexdigest()
            self.value = json.loads(self.raw, object_pairs_hook=closed_object)
            value = self.value
            required = {"schema_version", "repo", "head_sha", "collector", "completeness", "files", "deleted_paths", "source_set_sha256", "created_utc"}
            if (set(value) != required or value["schema_version"] != 1 or value["repo"] != str(self.repo)
                    or value["completeness"] != COMPLETENESS or any(type(part) is not bool for part in value["completeness"].values())
                    or not isinstance(value["files"], dict)
                    or not isinstance(value["deleted_paths"], list) or not isinstance(value["head_sha"], str)
                    or len(value["head_sha"]) != 40 or any(part not in "0123456789abcdef" for part in value["head_sha"])):
                raise ManifestError("source manifest schema mismatch")
            files, deleted = value["files"], value["deleted_paths"]
            if (len(files) + len(deleted) > MAX_FILES or deleted != sorted(set(deleted))
                    or set(files) & set(deleted) or value["source_set_sha256"] != source_set_digest(files, deleted)):
                raise ManifestError("source manifest membership mismatch")
            for name in list(files) + deleted:
                safe_name(name)
            for entry in files.values():
                if (not isinstance(entry, dict) or set(entry) != {"sha256", "bytes", "mode"}
                        or type(entry["bytes"]) is not int or not 0 <= entry["bytes"] <= MAX_FILE_BYTES
                        or type(entry["mode"]) is not int or not 0 <= entry["mode"] <= 0o777
                        or not isinstance(entry["sha256"], str) or len(entry["sha256"]) != 64
                        or any(value not in "0123456789abcdef" for value in entry["sha256"])):
                    raise ManifestError("invalid source manifest record")
            if (COLLECTOR_NAME not in files or sum(entry["bytes"] for entry in files.values()) > MAX_TOTAL_BYTES
                    or value["collector"] != {"name": COLLECTOR_NAME, "sha256": files[COLLECTOR_NAME]["sha256"]}):
                raise ManifestError("collector identity missing")
            if source_record(self.repo, COLLECTOR_NAME)["sha256"] != hashlib.sha256(Path(__file__).read_bytes()).hexdigest():
                raise ManifestError("collector implementation mismatch")
            self.verify()
        except BaseException:
            self.close()
            raise

    def verify(self):
        named = os.stat(self.parent / MANIFEST_NAME, follow_symlinks=False)
        if stamp(named) != self.before or stamp(os.fstat(self.descriptor)) != self.before:
            raise ManifestError("source manifest changed")
        value = self.value
        current = snapshot(self.repo, value["files"], value["deleted_paths"])
        if current != value["files"]:
            raise ManifestError("source bytes or mode changed")
        return current

    def close(self):
        if self.descriptor is not None:
            os.close(self.descriptor)
            self.descriptor = None

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()


def verify_complete(repo, parent):
    with ManifestLease(repo, parent) as lease:
        head, names, deleted = git_members(lease.repo)
        if head != lease.value["head_sha"] or names != sorted(lease.value["files"]) or deleted != lease.value["deleted_paths"]:
            raise ManifestError("outer source completeness changed")
        return lease.raw_sha256


if __name__ == "__main__":
    assert len(sys.argv) == 4
    if sys.argv[1] == "collect":
        print(collect(sys.argv[2], sys.argv[3]))
    elif sys.argv[1] == "verify-complete":
        print(verify_complete(sys.argv[2], sys.argv[3]))
    else:
        raise SystemExit("unknown outer source-manifest command")
